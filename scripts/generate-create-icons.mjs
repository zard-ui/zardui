#!/usr/bin/env node
/**
 * Writes the per-family icon tables the /create preview swaps between.
 *
 * The CLI's `ICON_MAP` says which symbol each family uses for an icon token. The preview needs the SVG behind
 * every one of those symbols, and it must not bundle whole icon packages (tabler alone is several MB), so each
 * family gets a module of static named imports — tree-shakable, loaded on demand.
 *
 *   node scripts/generate-create-icons.mjs
 *
 * Re-run when `packages/cli/src/core/icons/icon-map.ts` changes.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { ICON_MAP } = await import(pathToFileURL(join(root, 'packages/cli/src/core/icons/icon-map.ts')).href);
const { ICON_FAMILIES } = await import(pathToFileURL(join(root, 'packages/cli/src/core/icons/families.ts')).href);

const TABLE = ICON_MAP;

const outDir = join(root, 'apps/web/src/app/domain/pages/create/data/icons');
mkdirSync(outDir, { recursive: true });

for (const [family, info] of Object.entries(ICON_FAMILIES)) {
  const entries = Object.entries(TABLE)
    .map(([token, row]) => [token, row[family]])
    .filter(([, symbol]) => Boolean(symbol))
    .sort(([a], [b]) => a.localeCompare(b));

  const symbols = [...new Set(entries.map(([, symbol]) => symbol))].sort();
  const from = info.importFrom ?? info.package;

  const body = [
    '// Generated by scripts/generate-create-icons.mjs from the CLI icon map — do not edit by hand.',
    `import { ${symbols.join(', ')} } from '${from}';`,
    '',
    `export const ICONS: Readonly<Record<string, string>> = {`,
    ...entries.map(([token, symbol]) => `  '${token}': ${symbol},`),
    '};',
    '',
  ].join('\n');

  writeFileSync(join(outDir, `${family}.ts`), body);
  console.log(`${family}: ${entries.length} icons`);
}
