import { expect, test, type Locator, type Page } from '@playwright/test';

import { checkA11y } from './utils/axe-helper';
import { ComponentDemoPage } from './utils/component-page';

const SECTIONS = [
  { id: 'overview', heading: 'RTL' },
  { id: 'get-started', heading: 'Get started' },
  { id: 'how-it-works', heading: 'How it works' },
  { id: 'font-recommendations', heading: 'Font recommendations' },
  { id: 'animations', heading: 'Animations' },
  { id: 'migrating', heading: 'Migrating existing components' },
];

/** Opens the language selector of an RTL preview and picks an option by its visible label. */
async function pickLanguage(page: Page, box: Locator, label: string): Promise<void> {
  await box.locator('[data-slot="rtl-preview-header"] [role="combobox"]').click();
  await page.getByRole('option', { name: label }).first().click();
}

test.describe('RTL guide (/docs/rtl)', () => {
  test.beforeEach(async ({ page }) => {
    await page.goto('/docs/rtl');
    await page.waitForSelector('#overview', { state: 'visible', timeout: 15_000 });
    await page.waitForLoadState('networkidle');
  });

  test('renders every section with its heading and anchor', async ({ page }) => {
    await expect(page).toHaveTitle(/RTL/);
    await expect(page.getByRole('heading', { level: 1, name: 'RTL' })).toBeVisible();

    for (const { id, heading } of SECTIONS.slice(1)) {
      await expect(page.locator(`section#${id}`)).toBeAttached();
      await expect(page.locator(`section#${id}`).getByRole('heading', { level: 2, name: heading })).toBeVisible();
    }
  });

  test('anchor navigation scrolls to the section', async ({ page }) => {
    const anchors = page.locator('z-dynamic-anchor');
    await anchors.getByText('Animations', { exact: true }).click();
    await expect(page).toHaveURL(/#animations$/);
    await expect(page.locator('section#animations')).toBeInViewport();
  });

  test('the intro card preview is rendered in RTL with the code hidden', async ({ page }) => {
    const box = page.locator('#overview z-code-box, z-code-box').first();
    const preview = box.locator('[data-slot="preview"]');

    await expect(preview).toHaveAttribute('dir', 'rtl');
    await expect(preview).toHaveAttribute('data-lang', 'ar');
    await expect(preview.locator('[z-card]')).toBeVisible();
    await expect(preview.getByText('مرحبا بعودتك')).toBeVisible();
    await expect(box.locator('z-code-block')).toHaveCount(0);
    await expect(box.getByRole('button', { name: 'View Code' })).toHaveCount(0);
  });

  test('switching the language flips the card live', async ({ page }) => {
    const box = page.locator('z-code-box').first();
    const preview = box.locator('[data-slot="preview"]');

    await pickLanguage(page, box, 'English');
    await expect(preview).toHaveAttribute('dir', 'ltr');
    await expect(preview.getByText('Welcome back')).toBeVisible();

    await pickLanguage(page, box, 'Hebrew');
    await expect(preview).toHaveAttribute('dir', 'rtl');
    await expect(preview).toHaveAttribute('data-lang', 'he');
  });

  test('is reachable from the sidebar', async ({ page }) => {
    // Listed under both "Sections" and "Get Started" on purpose (see routes.constant.ts).
    const links = page.locator('z-sidebar').getByRole('link', { name: 'RTL', exact: true });
    await expect(links).toHaveCount(2);
    await expect(links.first()).toBeVisible();
  });

  test('serves the markdown version of the page', async ({ request }) => {
    const response = await request.get('/docs/rtl.md');
    // Generated after the production build; the dev server only has it once the generator ran.
    test.skip(
      !response.ok() || (response.headers()['content-type'] ?? '').includes('html'),
      '/docs/rtl.md is generated by the build',
    );
    expect(await response.text()).toContain('# RTL');
  });

  test('has no accessibility violations', async ({ page }) => {
    // Shiki token colors in the code blocks are the same on every docs page: not part of this guide.
    await checkA11y(page, 'main', ['color-contrast']);
  });
});

test.describe('RTL preview in the code box (/docs/components/aspect-ratio)', () => {
  let rtlBox: Locator;
  let demoPage: ComponentDemoPage;

  test.beforeEach(async ({ page }) => {
    demoPage = new ComponentDemoPage(page, 'aspect-ratio');
    await demoPage.goto();
    rtlBox = demoPage.getDemoByName('rtl');
  });

  test('has the header bar with the language select on Arabic by default', async () => {
    const header = rtlBox.locator('[data-slot="rtl-preview-header"]');
    await expect(header).toBeVisible();
    await expect(header.locator('[role="combobox"]')).toContainText('العربية');
    await expect(header.getByRole('button', { name: 'About the translations' })).toBeVisible();
  });

  test('the preview carries dir and data-lang, and follows the selected language live', async ({ page }) => {
    const preview = rtlBox.locator('[data-slot="preview"]');
    await expect(preview).toHaveAttribute('dir', 'rtl');
    await expect(preview).toHaveAttribute('data-lang', 'ar');
    await expect(preview.getByText('منظر طبيعي جميل')).toBeVisible();

    await pickLanguage(page, rtlBox, 'Hebrew');
    await expect(preview).toHaveAttribute('dir', 'rtl');
    await expect(preview).toHaveAttribute('data-lang', 'he');
    await expect(preview.getByText('נוף יפהפה')).toBeVisible();

    await pickLanguage(page, rtlBox, 'English');
    await expect(preview).toHaveAttribute('dir', 'ltr');
    await expect(preview).toHaveAttribute('data-lang', 'en');
    await expect(preview.getByText('Beautiful landscape')).toBeVisible();
  });

  test('the language select itself stays left to right', async () => {
    await expect(rtlBox.locator('[data-slot="rtl-preview-header"] z-select')).toHaveAttribute('dir', 'ltr');
  });

  test('ordinary previews are explicitly left to right and have no header bar', async () => {
    const ordinary = demoPage.firstDemoBox.locator('[data-slot="preview"]');
    await expect(ordinary).toHaveAttribute('dir', 'ltr');
    await expect(ordinary).not.toHaveAttribute('data-lang', /.+/);
    await expect(demoPage.firstDemoBox.locator('[data-slot="rtl-preview-header"]')).toHaveCount(0);
  });

  test('the info button opens the note about the translations', async ({ page }) => {
    await rtlBox.getByRole('button', { name: 'About the translations' }).click();
    const note = page.locator('z-popover');
    await expect(note).toBeVisible();
    await expect(note.locator('p')).toHaveCount(3);
    await expect(note.locator('p[lang="ar"]')).toHaveAttribute('dir', 'rtl');
  });

  test('has no accessibility violations in the RTL example', async ({ page }) => {
    await checkA11y(page, '[id="rtl"]', ['color-contrast']);
    expect(page.url()).toContain('/docs/components/aspect-ratio');
  });
});
