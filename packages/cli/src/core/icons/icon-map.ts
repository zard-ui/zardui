/**
 * The translation table between icon sets.
 *
 * Each row is an icon by what it MEANS — `check`, `chevron-down` — and the
 * value is the symbol each set exports for it. `lucide` is the set the library
 * is written in; `tabler`, `hugeicons`, `phosphor` and `remixicon` are the others
 * a project can choose. A token a set has no equivalent for simply has no entry in
 * its column: `retargetIcons` reports it as `missing` and keeps the original
 * import working.
 *
 * This is the copy bundled with the CLI. It is published at
 * `<registry>/icons.json`, and that is where the CLI reads it from at run time
 * — the file here is what holds when the registry does not answer, and the
 * floor the published table is generated from.
 *
 * The list covers every icon the components, demos, blocks and the /create canvas use
 * today. A new icon in the code with no row here is an error: `icons.spec.ts` compares
 * this table against what `libs/zard`, `libs/blocks` and the canvas actually use, and
 * `npm run check:icons` fails the build for the same reason.
 *
 * The tokens come from the lucide name in kebab-case because that already is
 * the icon's semantic name (`lucideChevronDown` → `chevron-down`) — the key
 * belongs to the table, not to the set.
 *
 * Picking the equivalents: the outline style of each set (`tabler` outline,
 * `phosphor/regular`, remix `…Line`), and the nearest meaning when the name differs
 * (`chevron-down` is `phosphorCaretDown`). Every symbol was checked against the
 * exports of the installed `@ng-icons/*` packages; `icons.spec.ts` keeps it that way.
 */

